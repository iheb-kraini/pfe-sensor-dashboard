import { useState } from "react";
import {
  Badge,
  Box,
  Button,
  Flex,
  Heading,
  HStack,
  Skeleton,
  Table,
  Text,
} from "@chakra-ui/react";
import { LuBell } from "react-icons/lu";
import { useNotifications } from "../../hooks/useNotifications";
import type {
  Notification,
  NotificationState,
  SeverityLevel,
} from "../../types/notification.types";
import { NotificationDrawer } from "../../components/notifications/Notificationdrawer";
import { NotificationFilters } from "../../components/notifications/Notificationfilters";

const SEVERITY_PALETTE: Record<string, string> = {
  low: "blue",
  medium: "yellow",
  high: "orange",
  critical: "red",
};

const STATE_PALETTE: Record<string, string> = {
  unread: "gray",
  in_investigation: "purple",
  resolved: "green",
  dismissed: "red",
};

const STATE_LABEL: Record<string, string> = {
  unread: "Unread",
  in_investigation: "In Investigation",
  resolved: "Resolved",
  dismissed: "Dismissed",
};

export function NotificationsPage() {
  const [state, setState] = useState<NotificationState | "">("");
  const [severity, setSeverity] = useState<SeverityLevel | "">("");
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");

  const filters = {
    ...(state && { state }),
    ...(severity && { severity }),
    ...(from && { from }),
    ...(to && { to }),
  };

  const hasFilters = !!state || !!severity || !!from || !!to;

  const resetFilters = () => {
    setState("");
    setSeverity("");
    setFrom("");
    setTo("");
  };

  const {
    notifications,
    isLoading,
    isError,
    page,
    totalPages,
    nextPage,
    prevPage,
    changeState,
  } = useNotifications(filters);

  const [selected, setSelected] = useState<Notification | null>(null);

  return (
    <Box p={6}>
      <Box mb={6}>
        <Heading size="lg">Notifications</Heading>
        <Text color="gray.500" fontSize="sm" mt={1}>
          Alerts generated by your devices
        </Text>
      </Box>

      <NotificationFilters
        state={state}
        severity={severity}
        from={from}
        to={to}
        hasFilters={hasFilters}
        onStateChange={setState}
        onSeverityChange={setSeverity}
        onFromChange={setFrom}
        onToChange={setTo}
        onReset={resetFilters}
      />

      {isError && (
        <Box bg="red.50" color="red.600" px={4} py={3} rounded="md" mb={4}>
          Failed to load notifications. Please try again.
        </Box>
      )}

      <Table.Root variant="outline" rounded="md">
        <Table.Header>
          <Table.Row>
            <Table.ColumnHeader>Severity</Table.ColumnHeader>
            <Table.ColumnHeader>Message</Table.ColumnHeader>
            <Table.ColumnHeader>Device</Table.ColumnHeader>
            <Table.ColumnHeader>State</Table.ColumnHeader>
            <Table.ColumnHeader>Date</Table.ColumnHeader>
          </Table.Row>
        </Table.Header>
        <Table.Body>
          {isLoading ? (
            Array.from({ length: 5 }).map((_, i) => (
              <Table.Row key={i}>
                {Array.from({ length: 5 }).map((_, j) => (
                  <Table.Cell key={j}>
                    <Skeleton h="20px" rounded="md" />
                  </Table.Cell>
                ))}
              </Table.Row>
            ))
          ) : notifications.length === 0 ? (
            <Table.Row>
              <Table.Cell
                colSpan={5}
                textAlign="center"
                py={8}
                color="gray.400"
              >
                <Flex direction="column" align="center" gap={2}>
                  <Box opacity={0.4}><LuBell size={32} /></Box>
                  <Text fontSize="sm">No notifications found</Text>
                </Flex>
              </Table.Cell>
            </Table.Row>
          ) : (
            notifications.map((n, i) => (
              <Table.Row
                key={n.id}
                cursor="pointer"
                _hover={{ bg: "gray.100" }}
                onClick={() => setSelected(n)}
                bg={n.state === "unread" ? "orange.50" : i % 2 === 0 ? "white" : "gray.50"}
              >
                <Table.Cell>
                  <Badge
                    colorPalette={SEVERITY_PALETTE[n.severity]}
                    textTransform="capitalize"
                  >
                    {n.severity}
                  </Badge>
                </Table.Cell>
                <Table.Cell
                  maxW="320px"
                  overflow="hidden"
                  textOverflow="ellipsis"
                  whiteSpace="nowrap"
                  fontWeight={n.state === "unread" ? "semibold" : "normal"}
                  fontSize="sm"
                >
                  {n.message}
                </Table.Cell>
                <Table.Cell color="gray.500" fontSize="sm">
                  {n.device?.name ?? `Device #${n.deviceId}`}
                </Table.Cell>
                <Table.Cell>
                  <Badge colorPalette={STATE_PALETTE[n.state]}>
                    {STATE_LABEL[n.state]}
                  </Badge>
                </Table.Cell>
                <Table.Cell color="gray.500" fontSize="sm">
                  {new Date(n.createdAt).toLocaleDateString()}
                </Table.Cell>
              </Table.Row>
            ))
          )}
        </Table.Body>
      </Table.Root>

      {totalPages > 1 && (
        <HStack justify="center" mt={4} gap={2}>
          <Button
            size="sm"
            variant="outline"
            disabled={page === 1}
            onClick={prevPage}
          >
            Previous
          </Button>
          <Text fontSize="sm" color="gray.500">
            Page {page} of {totalPages}
          </Text>
          <Button
            size="sm"
            variant="outline"
            disabled={page === totalPages}
            onClick={nextPage}
          >
            Next
          </Button>
        </HStack>
      )}

      <NotificationDrawer
        notification={selected}
        onClose={() => setSelected(null)}
        onChangeState={changeState}
      />
    </Box>
  );
}
